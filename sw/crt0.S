# ============================================================
# crt0.S —— C 程序的启动代码（C Runtime 0）
#
# 为什么需要它？
#   C 程序天生假设"有人已经准备好运行环境"。裸机上没有操作系统，
#   所以开机第一件事必须由启动代码来做：
#     1) 把栈指针 sp 指向一块可用的内存（C 函数调用、局部变量要用栈）
#     2) 把 .bss 段清零（C 语言规定未初始化的全局变量初值为 0，
#        但它们在内存里是随机的，必须由启动代码清零）
#     3) 调用 main()（C 程序真正的入口）
#   C 语言规定程序从 main 开始，但 CPU 复位后是从 _start 开始取指令，
#   crt0.S 就是这两者之间的那座桥。
#
# 存储器地址图（统一存储器扩到 128KB）：
#   0x00000 - 0x0FFFF  程序镜像（.text/.rodata/.data/.bss）
#   0x10000 - 0x3FFFC  堆 / 动态数据
#   0x3FFFC 起向下      栈（RAM 顶端 0x3FFFF，故栈顶取 0x3FFFC）
# ============================================================
    .section .text.start
    .globl _start
_start:
    # ---- 1) 设置栈指针 ----
    # 统一 RAM 共 128KB（0x00000 ~ 0x1FFFF），栈从顶端向下生长，
    # 栈顶取最高 4 字节对齐地址 0x3FFFC。
    li   sp, 0x0003FFFC

    # ---- 2) 清零 .bss 段 ----
    # __bss_start / __bss_end 由链接脚本（link_c.ld）提供。
    la   t0, __bss_start
    la   t1, __bss_end
1:
    bgeu t0, t1, 2f          # t0 >= t1 就结束
    sw   x0, 0(t0)           # 写 0
    addi t0, t0, 4
    j    1b
2:

    # ---- 3) 跳进 C 语言的 main() ----
    call main

    # main 如果真的返回了（正常情况它不该返回），就死循环停住
3:  j    3b

    # ============================================================
    # 【布局旋钮】链接时插入 LAYOUT_PAD 字节填充。
    #   本核对"指令落在哪条 8/16 字节边界"极其敏感：同一份程序，
    #   代码整体挪 168 字节，跑分能差 0.8%。用它做一次布局搜索：
    #     py scripts\build_coremark.py ... -D LAYOUT_PAD=24
    #   不定义时就是 0，不影响正常构建。
    # ============================================================
#ifdef LAYOUT_PAD
    .section .text
    .space LAYOUT_PAD
#endif